/* =========================================================
   PDF HELPERS
========================================================= */

const PDFSection = ({ title, children }) => (
  <View wrap={false}>
    <Text style={pdfStyles.sectionTitle}>{title}</Text>
    {children}
  </View>
);

const PDFBulletList = ({ items }) => {
  if (!Array.isArray(items)) return null;

  return (
    <View>
      {items.map((item, index) => (
        <Text key={index} style={pdfStyles.bullet}>
          • {item}
        </Text>
      ))}
    </View>
  );
};

const PDFParagraph = ({ text }) => {
  if (!text) return null;

  return <Text style={pdfStyles.paragraph}>{text}</Text>;
};

/* =========================================================
   VALIDATION PDF
========================================================= */


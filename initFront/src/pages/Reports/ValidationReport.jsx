/* =========================================================
   UI HELPERS
========================================================= */

const Section = ({ title, icon: Icon, children }) => {
  return (
    <section className="mb-8">
      <div className="flex items-center gap-3 mb-4">
        {Icon && (
          <div className="w-10 h-10 rounded-xl bg-violet-100 flex items-center justify-center">
            <Icon className="w-5 h-5 text-violet-600" />
          </div>
        )}

        <h2 className="text-xl font-semibold text-gray-900">{title}</h2>
      </div>

      {children}
    </section>
  );
};

const BulletList = ({ items }) => {
  if (!Array.isArray(items) || items.length === 0) {
    return <p className="text-gray-500">No information available.</p>;
  }

  return (
    <ul className="space-y-3">
      {items.map((item, index) => (
        <li key={index} className="flex gap-3 text-gray-700 leading-7">
          <span className="mt-2 w-2 h-2 rounded-full bg-violet-500 flex-shrink-0" />

          <span>{item}</span>
        </li>
      ))}
    </ul>
  );
};

const ReportCard = ({ children }) => {
  return (
    <div className="bg-white border border-gray-200 rounded-2xl p-6 shadow-sm">
      {children}
    </div>
  );
};

const HeaderMeta = ({ label, value }) => {
  return (
    <div>
      <p className="text-xs text-gray-500 mb-1">{label}</p>

      <p className="text-sm font-medium text-gray-800">{value}</p>
    </div>
  );
};

/* =========================================================
   MAIN COMPONENT
========================================================= */

const ValidationReport = () => {
  const navigate = useNavigate();
  const { validationId } = useParams();

  const [report, setReport] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  /* =======================================================
     FETCH REPORT
  ======================================================= */

  useEffect(() => {
    const userGetReport = async () => {
      try {
        setLoading(true);
        setError("");

        const response = await fetch(
          `http://localhost:3000/api/validation/${validationId}`,
        );

        if (!response.ok) {
          throw new Error("Failed to fetch validation report");
        }

        const data = await response.json();

        console.log("API Response:", data);

        setReport(data);
      } catch (err) {
        console.error("Get validation report error:", err);

        setError(err.message || "Failed to load validation report.");
      } finally {
        setLoading(false);
      }
    };

    if (validationId) {
      userGetReport();
    }
  }, [validationId]);

  /* =======================================================
     LOADING
  ======================================================= */

  if (loading) {
    return (
      <div className="min-h-screen bg-gray-50 flex items-center justify-center">
        <div className="text-center">
          <div className="w-10 h-10 border-4 border-violet-200 border-t-violet-600 rounded-full animate-spin mx-auto mb-4" />

          <p className="text-gray-600">Loading validation report...</p>
        </div>
      </div>
    );
  }

  /* =======================================================
     ERROR
  ======================================================= */

  if (error) {
    return (
      <div className="min-h-screen bg-gray-50 flex items-center justify-center px-6">
        <div className="bg-white border border-red-200 rounded-2xl p-8 max-w-md w-full text-center shadow-sm">
          <AlertTriangle className="w-12 h-12 text-red-500 mx-auto mb-4" />

          <h2 className="text-xl font-semibold text-gray-900 mb-2">
            Unable to load report
          </h2>

          <p className="text-gray-600 mb-6">{error}</p>

          <button
            onClick={() => navigate(-1)}
            className="px-5 py-2.5 rounded-lg bg-violet-600 text-white hover:bg-violet-700 transition"
          >
            Go Back
          </button>
        </div>
      </div>
    );
  }

  /* =======================================================
     NO REPORT
  ======================================================= */

  if (!report || !report.validationReport) {
    return (
      <div className="min-h-screen bg-gray-50 flex items-center justify-center">
        <div className="text-center">
          <FileText className="w-12 h-12 text-gray-400 mx-auto mb-4" />

          <h2 className="text-xl font-semibold text-gray-900 mb-2">
            Report not found
          </h2>

          <p className="text-gray-500">No validation report data was found.</p>
        </div>
      </div>
    );
  }

  /* =======================================================
     ACTUAL VALIDATION REPORT DATA
  ======================================================= */

  const data = report.validationReport;

  const filename = `${data.title || "validation-report"}`
    .replace(/[^a-z0-9]/gi, "-")
    .toLowerCase();

  /* =======================================================
     RENDER
  ======================================================= */

  return (
    <div className="min-h-screen bg-gray-50">
      {/* ===================================================
          TOP NAVIGATION
      =================================================== */}

      <div className="sticky top-0 z-40 bg-white border-b border-gray-200">
        <div className="max-w-7xl mx-auto px-6 py-4 flex items-center justify-between">
          <button
            onClick={() => navigate(-1)}
            className="flex items-center gap-2 text-gray-600 hover:text-gray-900 transition"
          >
            <ArrowLeft className="w-5 h-5" />

            <span className="font-medium">Back</span>
          </button>

          <PDFDownloadLink
            document={<ValidationPDF report={report} />}
            fileName={`${filename}.pdf`}
          >
            {({ loading: pdfLoading }) => (
              <button
                disabled={pdfLoading}
                className="flex items-center gap-2 px-4 py-2.5 bg-violet-600 text-white rounded-lg hover:bg-violet-700 disabled:opacity-60 transition"
              >
                <Download className="w-4 h-4" />

                {pdfLoading ? "Preparing PDF..." : "Download PDF"}
              </button>
            )}
          </PDFDownloadLink>
        </div>
      </div>

      {/* ===================================================
          MAIN CONTENT
      =================================================== */}

      <main className="max-w-7xl mx-auto px-6 py-10">
        {/* =================================================
            HEADER
        ================================================= */}

        <div className="mb-10">
          <div className="flex items-start justify-between gap-8">
            <div>
              <div className="inline-flex items-center gap-2 px-3 py-1.5 rounded-full bg-violet-100 text-violet-700 text-sm font-medium mb-4">
                <CheckCircle className="w-4 h-4" />
                Validation Report
              </div>

              <h1 className="text-3xl md:text-4xl font-bold text-gray-900 leading-tight">
                {data.title}
              </h1>

              <p className="mt-3 text-gray-500 max-w-3xl">
                AI-generated startup validation report.
              </p>
            </div>
          </div>

          {/* METADATA */}

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 mt-8 max-w-xl">
            <div className="bg-white border border-gray-200 rounded-xl p-4">
              <HeaderMeta label="Validation ID" value={report.validationId} />
            </div>

            <div className="bg-white border border-gray-200 rounded-xl p-4">
              <HeaderMeta label="Report" value="Startup Validation" />
            </div>
          </div>
        </div>

        {/* =================================================
            EXECUTIVE SUMMARY
        ================================================= */}

        <Section title="Executive Summary" icon={FileText}>
          <ReportCard>
            <div className="whitespace-pre-line text-gray-700 leading-8">
              {data.Report}
            </div>
          </ReportCard>
        </Section>

        {/* =================================================
            PROBLEM
        ================================================= */}

        <Section title="Problem" icon={Target}>
          <ReportCard>
            <BulletList items={data.Problem} />
          </ReportCard>
        </Section>

        {/* =================================================
            MARKET SIZE
        ================================================= */}

        <Section title="Market Size" icon={TrendingUp}>
          <ReportCard>
            <BulletList items={data.Market_size} />
          </ReportCard>
        </Section>

        {/* =================================================
            MARKET DEMAND
        ================================================= */}

        <Section title="Market Demand" icon={Users}>
          <ReportCard>
            <BulletList items={data.Market_demand} />
          </ReportCard>
        </Section>

        {/* =================================================
            COMPETITOR ANALYSIS
        ================================================= */}

        <Section title="Competitor Analysis" icon={Users}>
          <ReportCard>
            <BulletList items={data.Competitor} />
          </ReportCard>
        </Section>

        {/* =================================================
            MARKET TRENDS
        ================================================= */}

        <Section title="Market Trends" icon={TrendingUp}>
          <ReportCard>
            <BulletList items={data.Market_trend} />
          </ReportCard>
        </Section>

        {/* =================================================
            MONETIZATION
        ================================================= */}

        <Section title="Monetization" icon={DollarSign}>
          <ReportCard>
            <BulletList items={data.Monetization} />
          </ReportCard>
        </Section>

        {/* =================================================
            RISKS
        ================================================= */}

        <Section title="Risks" icon={ShieldAlert}>
          <ReportCard>
            <BulletList items={data.Risk} />
          </ReportCard>
        </Section>

        {/* =================================================
            FOOTER
        ================================================= */}

        <div className="border-t border-gray-200 mt-12 pt-8 pb-10">
          <div className="flex items-center justify-center gap-2 text-gray-400 text-sm">
            <Lightbulb className="w-4 h-4" />

            <span>Generated by InitWay AI</span>
          </div>
        </div>
      </main>
    </div>
  );
};

export default ValidationReport;

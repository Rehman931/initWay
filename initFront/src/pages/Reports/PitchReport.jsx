  const { pitchId } = useParams();
  const projectId = pitchId;
  const navigate = useNavigate();

  const [pitch, setPitch] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  /* ---------------------------------------------------------
     FETCH PITCH REPORT
  --------------------------------------------------------- */

  useEffect(() => {
    if (!projectId) {
      setError("Project ID is missing from the URL.");
      setLoading(false);
      return;
    }

    const controller = new AbortController();

    const fetchPitchReport = async () => {
      try {
        setLoading(true);
        setError("");

        const token = getAuthToken();

        const response = await fetch(`${API_URL}/api/pitch/${projectId}`, {
          method: "GET",
          headers: {
            "Content-Type": "application/json",
            ...(token
              ? {
                  Authorization: `Bearer ${token}`,
                }
              : {}),
          },
          signal: controller.signal,
        });

        let payload = null;

        try {
          payload = await response.json();
        } catch {
          payload = null;
        }

        if (!response.ok) {
          throw new Error(
            payload?.message ||
              payload?.error ||
              `Failed to load pitch report (${response.status})`,
          );
        }

        /*
          Supports multiple possible API response shapes:

          {
            pitchReport: {...}
          }

          {
            data: {
              pitchReport: {...}
            }
          }

          {
            report: {
              pitchReport: {...}
            }
          }
        */

        const report =
          payload?.pitchReport ||
          payload?.data?.pitchReport ||
          payload?.report?.pitchReport ||
          payload?.data ||
          payload?.report ||
          payload;

        if (!report || typeof report !== "object") {
          throw new Error("Pitch report data was not found.");
        }

        setPitch({
          ...report,
          createdAt:
            report?.createdAt ||
            payload?.createdAt ||
            payload?.data?.createdAt ||
            payload?.report?.createdAt,
        });
      } catch (err) {
        if (err.name === "AbortError") return;

        setError(err.message || "Unable to load the pitch report.");
      } finally {
        setLoading(false);
      }
    };

    fetchPitchReport();

    return () => controller.abort();
  }, [projectId]);

  /* ---------------------------------------------------------
     DERIVED DATA
  --------------------------------------------------------- */

  const generatedDate = useMemo(() => {
    return formatDate(pitch?.createdAt);
  }, [pitch?.createdAt]);


const safeText = (value, fallback = "Not provided") => {
  if (value === null || value === undefined || value === "") {
    return fallback;
  }

  return String(value);
};

const formatDate = (value) => {
  if (!value) return "Generated by InitWay";

  const date = new Date(value);

  if (Number.isNaN(date.getTime())) {
    return String(value);
  }

  return date.toLocaleDateString("en-US", {
    month: "long",
    day: "numeric",
    year: "numeric",
  });
};

const parseNumberedList = (text) => {
  if (!text) return [];

  const value = String(text);

  const items = value
    .split(/\s*(?:^|\s)\d+\)\s*/g)
    .map((item) => item.trim())
    .filter(Boolean);

  if (items.length > 1) {
    return items;
  }

  return value
    .split(/[•\n]/)
    .map((item) => item.trim())
    .filter(Boolean);
};

